    init?(_ provider: Provider) {
        guard let data = Self.pathData(provider) else { return nil }
        commands = Self.parse(data)
    }

    func path(in rect: CGRect) -> Path {
        let scale = min(rect.width, rect.height) / 24
        let origin = CGPoint(x: rect.midX - 12 * scale, y: rect.midY - 12 * scale)
        func point(_ values: [CGFloat], _ index: Int) -> CGPoint {
            CGPoint(x: origin.x + values[index] * scale, y: origin.y + values[index + 1] * scale)
        }
        var path = Path()
        for (command, values) in commands {
            switch command {
            case "M": path.move(to: point(values, 0))
            case "L": path.addLine(to: point(values, 0))
            case "C": path.addCurve(to: point(values, 4), control1: point(values, 0), control2: point(values, 2))
            default: path.closeSubpath()
            }
        }
        return path
    }

    /// Reads the absolute `M`, `L`, `C` and `Z` commands the paths below are written in.
    static func parse(_ data: String) -> [(Character, [CGFloat])] {
        var commands: [(Character, [CGFloat])] = []
        var scanner = data[...]
        while let command = scanner.first {
            scanner = scanner.dropFirst()
            let end = scanner.firstIndex { "MLCZ".contains($0) } ?? scanner.endIndex
            let values = scanner[..<end].split(separator: " ").compactMap { Double($0) }.map { CGFloat($0) }
            let arity = ["M": 2, "L": 2, "C": 6, "Z": 0][command] ?? 0
            if values.count == arity { commands.append((command, values)) }
            scanner = scanner[end...]
        }
        return commands
    }

